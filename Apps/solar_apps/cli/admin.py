"""Administration commands for the ignored local runtime tree."""

from __future__ import annotations

import argparse
import os
import shlex
import shutil
from pathlib import Path

from solar_apps.platform.layout import RuntimeLayout
from solar_apps.platform.migration import migrate_legacy_state

_POWERSHELL_SHIM = r"""# Generated by `solar_apps admin init`; this file stays in ignored Local/.
$ErrorActionPreference = "Stop"
$env:SOLAR_APPS_LOCAL_ROOT = $PSScriptRoot
$workspaceRoot = __REPOSITORY_TARGET__
$launcher = Join-Path $workspaceRoot "Apps\run.ps1"
& $launcher @args
exit $LASTEXITCODE
"""

_SHELL_SHIM = """#!/bin/sh
# Generated by `solar_apps admin init`; this file stays in ignored Local/.
set -eu
runtime_root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
workspace_root=$(CDPATH= cd -- __REPOSITORY_TARGET__ && pwd)
export SOLAR_APPS_LOCAL_ROOT="$runtime_root"
exec "$workspace_root/Apps/run.sh" "$@"
"""


def _runtime_shims(layout: RuntimeLayout) -> tuple[str, str]:
    """Keep external runtimes usable when their containing workspace moves."""
    try:
        relative = os.path.relpath(layout.repo_root, layout.local_root)
    except ValueError:  # Windows paths on different volumes cannot be relative.
        relative = None
    if relative is None:
        ps_path = str(layout.repo_root).replace("'", "''")
        ps_target = f"[System.IO.Path]::GetFullPath('{ps_path}')"
        shell_target = shlex.quote(layout.repo_root.as_posix())
    else:
        ps_path = relative.replace("/", "\\").replace("'", "''")
        ps_target = (
            "[System.IO.Path]::GetFullPath(" f"(Join-Path $PSScriptRoot '{ps_path}'))"
        )
        shell_target = '"$runtime_root"/' + shlex.quote(relative.replace(os.sep, "/"))
    return (
        _POWERSHELL_SHIM.replace("__REPOSITORY_TARGET__", ps_target),
        _SHELL_SHIM.replace("__REPOSITORY_TARGET__", shell_target),
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="solar-apps admin",
        description="Initialize the private Local runtime tree.",
    )
    commands = parser.add_subparsers(dest="command", required=True)
    initialize = commands.add_parser("init", help="Create Local runtime directories.")
    initialize.add_argument(
        "--force-config",
        action="store_true",
        help="Replace paths.local.yaml with the public empty-root template.",
    )
    return parser


def initialize_runtime(
    *,
    layout: RuntimeLayout | None = None,
    force_config: bool = False,
) -> tuple[Path, ...]:
    """Create runtime directories, a safe config, and the compatibility shim."""

    selected = (layout or RuntimeLayout.discover()).ensure()
    template = selected.apps_root / "configs" / "examples" / "paths.example.yaml"
    if not template.is_file():
        raise FileNotFoundError(f"Application config template is missing: {template}")
    created: list[Path] = []
    powershell_content, shell_content = _runtime_shims(selected)
    if not force_config:
        created.extend(migrate_legacy_state(layout=selected))
    if force_config or not selected.config_path.exists():
        shutil.copyfile(template, selected.config_path)
        created.append(selected.config_path)
    powershell_shim = selected.local_root / "run.ps1"
    if (
        not powershell_shim.exists()
        or powershell_shim.read_text(encoding="utf-8-sig") != powershell_content
    ):
        powershell_shim.write_text(powershell_content, encoding="utf-8", newline="\n")
        created.append(powershell_shim)
    shell_shim = selected.local_root / "run.sh"
    if (
        not shell_shim.exists()
        or shell_shim.read_text(encoding="utf-8") != shell_content
    ):
        shell_shim.write_text(shell_content, encoding="utf-8", newline="\n")
        created.append(shell_shim)
    shell_shim.chmod(shell_shim.stat().st_mode | 0o111)
    return tuple(created)


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "init":
            created = initialize_runtime(force_config=args.force_config)
        else:  # pragma: no cover - argparse guards this branch
            parser.error(f"Unknown admin command: {args.command}")
            return 2
    except OSError as exc:
        parser.exit(2, f"admin: error: {exc}\n")
    if created:
        print("Initialized Local runtime files:")
        for path in created:
            print(f"  {path}")
    else:
        print("Local runtime is already initialized.")
    return 0


__all__ = ["build_parser", "initialize_runtime", "main"]
