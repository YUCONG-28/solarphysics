def _p(
    parameter_id: str,
    label: str,
    kind: str = "string",
    *,
    default: Any = None,
    required: bool = False,
    advanced: bool = False,
    flag: str | None = None,
    aliases: tuple[str, ...] = (),
    negative: str | None = None,
    positional: bool = False,
    choices: tuple[Any, ...] = (),
    minimum: float | None = None,
    maximum: float | None = None,
    unit: str = "",
    help_text: str = "",
    config_path: str | None = None,
    extensions: tuple[str, ...] = (),
    list_style: str = "comma",
    conflicts: tuple[str, ...] = (),
    requires: tuple[str, ...] = (),
    item_kind: str | None = None,
) -> ParameterSpec:
    return ParameterSpec(
        parameter_id=parameter_id,
        label=label,
        kind=kind,  # type: ignore[arg-type]
        default=default,
        required=required,
        group="advanced" if advanced else "common",
        cli_flag=flag,
        cli_aliases=aliases,
        negative_cli_flag=negative,
        positional=positional,
        choices=choices,
        minimum=minimum,
        maximum=maximum,
        unit=unit,
        help_text=help_text,
        config_path=config_path,
        path_extensions=extensions,
        conflicts_with=conflicts,
        requires=requires,
        allow_empty=not required,
        item_kind=item_kind,
        list_style=list_style,  # type: ignore[arg-type]
    )


def _in(
    port_id: str,
    label: str,
    *types: str,
    required: bool = False,
    parameter_id: str | None = None,
) -> ArtifactPortSpec:
    return ArtifactPortSpec(
        port_id,
        label,
        tuple(types),
        required=required,
        parameter_id=parameter_id,
    )


def _out(port_id: str, label: str, *types: str, multiple: bool = False) -> ArtifactPortSpec:
    return ArtifactPortSpec(
        port_id,
        label,
        tuple(types),
        required=False,
        multiple=multiple,
    )


