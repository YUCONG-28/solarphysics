def page_template(module_id: str) -> AppV1FlowV1:
    try:
        function_ids = PAGE_TEMPLATE_FUNCTIONS[module_id]
    except KeyError as exc:
        raise KeyError(f"Unknown page workflow template: {module_id}") from exc
    nodes = tuple(
        FlowNodeV1(
            node_id=f"node-{index}",
            function_id=function_id,
            parameters={},
            x=float(((index - 1) % 5) * 250),
            y=float(((index - 1) // 5) * 120),
        )
        for index, function_id in enumerate(function_ids, start=1)
    )
    edges: list[FlowEdgeV1] = []
    if module_id == "radio-composite":
        edges.extend(
            (
                FlowEdgeV1("node-1", "images", "node-3", "maps"),
                FlowEdgeV1("node-2", "spectrum", "node-3", "spectrum"),
            )
        )
    elif module_id == "dart-spectrogram":
        edges.extend(
            (
                FlowEdgeV1("node-1", "spectrum", "node-2", "spectrum"),
                FlowEdgeV1("node-2", "drift", "node-3", "drift"),
            )
        )
    elif module_id == "source-trajectory":
        edges.append(
            FlowEdgeV1("node-1", "centers", "node-2", "centers_input")
        )
    return AppV1FlowV1(
        flow_id=f"{module_id}-default",
        name=f"{module_id.replace('-', ' ').title()} Default",
        nodes=nodes,
        edges=tuple(edges),
        saved_at_utc=datetime.now(timezone.utc),
    )


